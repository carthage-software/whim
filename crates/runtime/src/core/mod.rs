macro_rules! default_built_in_state {
    ($name:ident) => {
        impl $name {
            pub(crate) fn new(
                _vm: &mut $crate::vm::VirtualMachine<'_>,
            ) -> Result<Self, $crate::builtin::throw::Throw> {
                Ok(Self::default())
            }
        }
    };
}

